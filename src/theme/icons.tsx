/** Stable app-level icon names. Keeping this adapter avoids coupling screens to one icon package. */
export interface IconProps { size?: number; color?: string; strokeWidth?: number; style?: unknown }
function make(Icon: ComponentType<any>) {
  return function EvridaIcon({ size = 20, color, strokeWidth = 1.8, style }: IconProps) {
    return <Icon size={size} color={color} strokeWidth={strokeWidth} style={style} />;
  };
}

